#!/usr/bin/env python3
"""Build the standalone browser package; model declarations come from the existing ts-rs output."""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "packages/culprit-wasm"
OUTPUT = PACKAGE / "pkg"
BINDINGS = ROOT / "app/src/gen"
THIRD_PARTY_NOTICES = ROOT / "target/licenses/THIRD-PARTY-LICENSES.txt"
PACKAGED_WASM_STACK_BYTES = 32 * 1024 * 1024
MODEL_ROOTS = ("Plan", "PlanDiff", "Deadlock", "Engine", "CompareContext", "ExportFile", "ExportFormat", "ExportOptions", "ExtendedEventsBatch", "ExtendedEventsFormat", "NativeLogLimits", "Error")
IMPORT = re.compile(r'(from\s+["\'])(\./[^"\']+)(["\'])')


def run(*args: str, capture: bool = False) -> subprocess.CompletedProcess[str]:
    return subprocess.run(args, cwd=ROOT, text=True, check=True, capture_output=capture)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prerequisites(bindgen: str) -> dict[str, object]:
    required = ("cargo", "rustup", "node")
    missing = [name for name in required if shutil.which(name) is None]
    bindgen_path = shutil.which(bindgen)
    if bindgen_path is None:
        missing.append(f"wasm-bindgen executable {bindgen}")
    targets = run("rustup", "target", "list", "--installed", capture=True).stdout.splitlines() if shutil.which("rustup") else []
    if "wasm32-unknown-unknown" not in targets:
        missing.append("rust target wasm32-unknown-unknown")
    compiler = ROOT / "app/node_modules/typescript/bin/tsc"
    if not compiler.is_file():
        missing.append("existing app TypeScript installation")
    if not THIRD_PARTY_NOTICES.is_file() or THIRD_PARTY_NOTICES.stat().st_size == 0:
        missing.append("shared third-party notices: python3 dev/licenses.py")
    lock = tomllib.loads((ROOT / "Cargo.lock").read_text())
    versions = sorted({p["version"] for p in lock["package"] if p["name"] == "wasm-bindgen"})
    actual = run(bindgen, "--version", capture=True).stdout.strip().split()[-1] if bindgen_path else None
    if actual is not None and versions != [actual]:
        missing.append(f"wasm-bindgen CLI matching the single locked version {versions}")
    return {"missing": missing, "installed_targets": targets, "locked_bindgen_versions": versions, "bindgen_cli_version": actual, "bindgen_executable": bindgen_path}


def declaration_closure() -> list[dict[str, object]]:
    pending = list(MODEL_ROOTS)
    found: dict[str, str] = {}
    while pending:
        name = pending.pop()
        if name in found:
            continue
        if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", name):
            raise ValueError(f"nonportable generated model reference: {name}")
        source = BINDINGS / f"{name}.ts"
        text = source.read_text()
        if "This file was generated by [ts-rs]" not in text:
            raise ValueError(f"model is not existing ts-rs output: {source}")
        found[name] = text
        for match in IMPORT.finditer(text):
            dependency = match[2][2:]
            if "/" in dependency or "." in dependency:
                raise ValueError(f"unexpected generated model import: {match[2]}")
            pending.append(dependency)
    models = OUTPUT / "models"
    models.mkdir(parents=True, exist_ok=True)
    manifest = []
    for name, text in sorted(found.items()):
        # Declaration-only packaging changes module extensions, never model fields or optionality.
        portable = IMPORT.sub(lambda m: f"{m[1]}{m[2]}.js{m[3]}", text)
        target = models / f"{name}.d.ts"
        target.write_text(portable)
        manifest.append({"name": name, "source_sha256": digest(BINDINGS / f"{name}.ts"), "package_sha256": digest(target)})
    return manifest


def sizes() -> dict[str, object]:
    result = {}
    for path in sorted(OUTPUT.rglob("*")):
        if path.suffix not in (".wasm", ".js"):
            continue
        value = path.read_bytes()
        script = 'import {brotliCompressSync,constants} from "node:zlib";import {readFileSync} from "node:fs";process.stdout.write(String(brotliCompressSync(readFileSync(process.argv[1]),{params:{[constants.BROTLI_PARAM_QUALITY]:11}}).length));'
        brotli = int(run("node", "--input-type=module", "-e", script, str(path), capture=True).stdout)
        result[str(path.relative_to(OUTPUT))] = {"bytes": len(value), "gzip_bytes": len(gzip.compress(value, compresslevel=9, mtime=0)), "brotli_bytes": brotli, "sha256": digest(path)}
    return result


def build(bindgen: str) -> None:
    available = prerequisites(bindgen)
    if available["missing"]:
        raise RuntimeError(json.dumps(available, indent=2))
    # Only disposable output is recreated. The existing Cargo cache/target/toolchain stays in place.
    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    native = OUTPUT / "native"
    native.mkdir(parents=True)
    shutil.copyfile(THIRD_PARTY_NOTICES, OUTPUT / THIRD_PARTY_NOTICES.name)
    # Match the existing Core XML budget on this final module only. Dependencies keep their cached flags.
    run("cargo", "rustc", "--locked", "-p", "culprit-wasm", "--lib", "--no-default-features", "--target", "wasm32-unknown-unknown", "--release", "--", "-C", f"link-arg=-zstack-size={PACKAGED_WASM_STACK_BYTES}")
    run(bindgen, str(ROOT / "target/wasm32-unknown-unknown/release/culprit_wasm.wasm"), "--target", "web", "--typescript", "--out-name", "culprit_wasm", "--out-dir", str(native))
    models = declaration_closure()
    run("node", str(ROOT / "app/node_modules/typescript/bin/tsc"), "--project", str(PACKAGE / "tsconfig.json"))
    run("node", str(ROOT / "app/node_modules/typescript/bin/tsc"), "--project", str(PACKAGE / "tsconfig.contract.json"))
    report = {"target": "wasm32-unknown-unknown", "profile": "release", "stack_policy": {"linear_stack_bytes": PACKAGED_WASM_STACK_BYTES, "scope": "final wasm crate only", "vm_call_stack": "requires actual browser acceptance"}, "tools": available, "cargo_lock_sha256": digest(ROOT / "Cargo.lock"), "models": models, "compression": {"gzip_level":9,"brotli_quality":11}, "artifacts": sizes(), "native_or_database_work": False}
    (OUTPUT / "build-report.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps({"package": str(PACKAGE), "models": len(models), "artifacts": report["artifacts"]}, indent=2))


def main() -> None:
    args = argparse.ArgumentParser(description=__doc__)
    args.add_argument("--check-prerequisites", action="store_true")
    args.add_argument("--bindgen", default="wasm-bindgen", help="Matching official wasm-bindgen executable; no global installation is required")
    options = args.parse_args()
    if options.check_prerequisites:
        available = prerequisites(options.bindgen)
        print(json.dumps(available, indent=2))
        raise SystemExit(bool(available["missing"]))
    build(options.bindgen)


if __name__ == "__main__":
    main()
