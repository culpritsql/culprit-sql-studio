#!/usr/bin/env python3
"""Build the standalone @culpritsql/plan-viewer React package from the monorepo source of truth."""
from __future__ import annotations

import argparse
import gzip
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "packages/culprit-plan-viewer"
SRC = PACKAGE / "src"
OUTPUT = PACKAGE / "pkg"
SCRATCH = ROOT / "target/plan-viewer-build"
BINDINGS = ROOT / "app/src/gen"
ENGINES_JSON = BINDINGS / "engines.json"
ENGLISH_JSON = ROOT / "locales/en.json"
CARDINALS_JSON = ROOT / "locales/.cldr/cardinals.json"
THIRD_PARTY_NOTICES = ROOT / "target/licenses/THIRD-PARTY-LICENSES.txt"

TS_GEN_EXPORT = re.compile(
    r'export\s+type\s+\{\s*([A-Za-z_][A-Za-z_0-9]*(?:\s+as\s+[A-Za-z_][A-Za-z_0-9]*)?)\s*\}\s+from\s+"../../../app/src/gen/([A-Za-z_][A-Za-z_0-9]*)";'
)
MODEL_IMPORT = re.compile(r'(from\s+["\'])(\./[^"\']+)(["\'])')
MESSAGE_KEY = re.compile(r'["\']((?:ui|common|view)\.[a-z0-9_.]+)["\']')
ANY_IMPORT = re.compile(r'(?:from|import)\s*["\']([^"\']+)["\']')
ALLOWED_EXTERNALS = {"react", "react/jsx-runtime", "lucide-react"}


def run(*args: str, capture: bool = False) -> subprocess.CompletedProcess[str]:
    return subprocess.run(args, cwd=ROOT, text=True, check=True, capture_output=capture)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prerequisites() -> dict[str, object]:
    missing: list[str] = []
    if shutil.which("node") is None:
        missing.append("node")
    tsc = ROOT / "app/node_modules/typescript/bin/tsc"
    if not tsc.is_file():
        missing.append("existing app TypeScript installation (cd app && bun install --frozen-lockfile)")
    if not (ROOT / "app/node_modules/@types/react/index.d.ts").is_file():
        missing.append("existing app @types/react installation")
    if not (ROOT / "app/node_modules/lucide-react/dist/lucide-react.d.ts").is_file():
        missing.append("existing app lucide-react installation")
    for required_file, label in (
        (ENGINES_JSON, "generated engines.json (cargo test --locked -p culprit-core --lib)"),
        (BINDINGS / "Plan.ts", "generated ts-rs bindings (app/src/gen/Plan.ts)"),
        (ENGLISH_JSON, "English message catalog (locales/en.json)"),
        (CARDINALS_JSON, "CLDR cardinal rules (locales/.cldr/cardinals.json)"),
        (THIRD_PARTY_NOTICES, "shared third-party notices (python3 dev/licenses.py)"),
    ):
        if not required_file.is_file() or required_file.stat().st_size == 0:
            missing.append(label)
    return {"missing": missing}


def parse_model_roots() -> tuple[list[tuple[str, str]], list[str]]:
    types_src = (SRC / "types.ts").read_text()
    exports: list[tuple[str, str]] = []
    roots: list[str] = []
    for line in types_src.splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        match = TS_GEN_EXPORT.fullmatch(stripped)
        if not match:
            raise ValueError(f"unexpected line in packages/culprit-plan-viewer/src/types.ts: {line}")
        specifier, model_name = match.group(1), match.group(2)
        exports.append((specifier, model_name))
        roots.append(model_name)
    return exports, roots


def declaration_closure(roots: list[str], models_out: Path) -> list[dict[str, object]]:
    pending = list(roots)
    found: dict[str, str] = {}
    while pending:
        name = pending.pop()
        if name in found:
            continue
        if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", name):
            raise ValueError(f"nonportable generated model reference: {name}")
        source = BINDINGS / f"{name}.ts"
        text = source.read_text()
        if "This file was generated by [ts-rs]" not in text:
            raise ValueError(f"model is not existing ts-rs output: {source}")
        found[name] = text
        for match in MODEL_IMPORT.finditer(text):
            dependency = match[2][2:]
            if "/" in dependency or "." in dependency:
                raise ValueError(f"unexpected generated model import: {match[2]}")
            pending.append(dependency)
    models_out.mkdir(parents=True, exist_ok=True)
    manifest = []
    for name, text in sorted(found.items()):
        portable = MODEL_IMPORT.sub(lambda m: f"{m[1]}{m[2]}.js{m[3]}", text)
        target = models_out / f"{name}.d.ts"
        target.write_text(portable)
        manifest.append(
            {
                "name": name,
                "source_sha256": digest(BINDINGS / f"{name}.ts"),
                "package_sha256": digest(target),
            }
        )
    return manifest


def collect_message_keys() -> list[str]:
    keys: set[str] = set()
    for path in sorted(SRC.glob("*.ts*")):
        if path.name in ("defaults.ts", "types.ts"):
            continue
        for match in MESSAGE_KEY.finditer(path.read_text()):
            keys.add(match.group(1))
    engines = json.loads(ENGINES_JSON.read_text())
    for spec in engines.values():
        ctx = spec.get("evidence_presentation", {}).get("generic_plan_context")
        if ctx:
            keys.add(ctx)
    english = json.loads(ENGLISH_JSON.read_text())
    missing = sorted(k for k in keys if k not in english)
    if missing:
        raise RuntimeError(f"plan-viewer references missing locales/en.json keys: {', '.join(missing)}")
    return sorted(keys)


def render_standalone_defaults(message_keys: list[str]) -> str:
    engines_raw = json.loads(ENGINES_JSON.read_text())
    engines = {
        key: {
            "label": spec["label"],
            "abilities": {"plan_estimates": bool(spec["abilities"]["plan_estimates"])},
            "products": [{"id": p["id"], "label": p["label"], "prefix": p["prefix"]} for p in spec["products"]],
            "evidence_presentation": {
                "generic_plan_context": spec["evidence_presentation"]["generic_plan_context"]
            },
        }
        for key, spec in sorted(engines_raw.items())
    }
    english_raw = json.loads(ENGLISH_JSON.read_text())
    raw_meta = english_raw["_meta"]
    locale_meta = {
        "plural": raw_meta["plural"],
        "decimal": raw_meta["decimal"],
        "group": raw_meta["group"],
        **({"direction": raw_meta["direction"]} if "direction" in raw_meta else {}),
    }
    messages = {k: english_raw[k] for k in message_keys}
    cardinals = json.loads(CARDINALS_JSON.read_text())
    return "\n".join(
        [
            'import type { Engine } from "./types.js";',
            "",
            "export type ViewerEngineSpec = {",
            "  label: string;",
            "  abilities: { plan_estimates: boolean };",
            "  products: { id: string; label: string; prefix: string | null }[];",
            "  evidence_presentation: { generic_plan_context: string };",
            "};",
            "",
            "export type ViewerLocaleMeta = {",
            "  plural: string;",
            "  decimal: string;",
            "  group: string;",
            '  direction?: "ltr" | "rtl";',
            "};",
            "",
            "export type CardinalRelation = [string, number, boolean, [number, number][]];",
            'export type PluralCategory = "zero" | "one" | "two" | "few" | "many" | "other";',
            "export type CardinalCase = [PluralCategory, CardinalRelation[][]];",
            "",
            f"export const DEFAULT_ENGINES: Record<Engine, ViewerEngineSpec> = {json.dumps(engines, ensure_ascii=False)};",
            f"export const DEFAULT_LOCALE: ViewerLocaleMeta = {json.dumps(locale_meta, ensure_ascii=False)};",
            f"export const DEFAULT_MESSAGES: Record<string, string> = {json.dumps(messages, ensure_ascii=False, indent=2)};",
            f"export const CARDINAL_LANGUAGES: Record<string, number> = {json.dumps(cardinals['languages'], ensure_ascii=False)};",
            f"export const CARDINAL_RULES: CardinalCase[][] = {json.dumps(cardinals['rules'], ensure_ascii=False)} as CardinalCase[][];",
            "",
        ]
    )


def verify_closed_imports() -> None:
    for path in sorted(OUTPUT.rglob("*")):
        if path.suffix not in (".js", ".ts"):
            continue
        text = path.read_text()
        for match in ANY_IMPORT.finditer(text):
            spec = match.group(1)
            if spec in ALLOWED_EXTERNALS:
                continue
            if not spec.startswith("./"):
                raise RuntimeError(f"non-closed module specifier in {path.relative_to(OUTPUT)}: {spec}")
            resolved = (path.parent / spec).resolve()
            if not resolved.is_relative_to(OUTPUT.resolve()):
                raise RuntimeError(f"import escapes pkg/ in {path.relative_to(OUTPUT)}: {spec}")


def sizes() -> dict[str, object]:
    result = {}
    brotli_script = (
        'import {brotliCompressSync,constants} from "node:zlib";'
        'import {readFileSync} from "node:fs";'
        "process.stdout.write(String(brotliCompressSync(readFileSync(process.argv[1]),"
        "{params:{[constants.BROTLI_PARAM_QUALITY]:11}}).length));"
    )
    for path in sorted(OUTPUT.rglob("*")):
        if not path.is_file() or path.suffix not in (".js", ".css"):
            continue
        raw = path.read_bytes()
        brotli = int(run("node", "--input-type=module", "-e", brotli_script, str(path), capture=True).stdout)
        result[path.relative_to(OUTPUT).as_posix()] = {
            "bytes": len(raw),
            "gzip_bytes": len(gzip.compress(raw, compresslevel=9, mtime=0)),
            "brotli_bytes": brotli,
            "sha256": digest(path),
        }
    return result


def build() -> None:
    available = prerequisites()
    if available["missing"]:
        raise RuntimeError(json.dumps(available, indent=2))

    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    if SCRATCH.exists():
        shutil.rmtree(SCRATCH)

    scratch_src = SCRATCH / "src"
    scratch_src.mkdir(parents=True)
    OUTPUT.mkdir(parents=True)

    exports, roots = parse_model_roots()
    models = declaration_closure(roots, OUTPUT / "models")
    shutil.copytree(OUTPUT / "models", scratch_src / "models")

    for src_file in sorted(SRC.glob("*.ts*")):
        if src_file.name in ("types.ts", "defaults.ts"):
            continue
        shutil.copyfile(src_file, scratch_src / src_file.name)

    types_lines = [f'export type {{ {spec} }} from "./models/{model}.js";' for spec, model in exports]
    (scratch_src / "types.ts").write_text("\n".join(types_lines) + "\n")

    message_keys = collect_message_keys()
    (scratch_src / "defaults.ts").write_text(render_standalone_defaults(message_keys))

    build_tsconfig = {
        "compilerOptions": {
            "target": "ES2022",
            "module": "ES2022",
            "moduleResolution": "Bundler",
            "lib": ["ES2023", "DOM", "DOM.Iterable"],
            "jsx": "react-jsx",
            "strict": True,
            "noUnusedLocals": True,
            "noUnusedParameters": True,
            "noFallthroughCasesInSwitch": True,
            "noUncheckedIndexedAccess": True,
            "declaration": True,
            "verbatimModuleSyntax": True,
            "noEmitOnError": True,
            "rootDir": "src",
            "outDir": str(OUTPUT),
            "types": [],
            "paths": {
                "react": [str(ROOT / "app/node_modules/@types/react/index.d.ts")],
                "react/jsx-runtime": [str(ROOT / "app/node_modules/@types/react/jsx-runtime.d.ts")],
                "lucide-react": [str(ROOT / "app/node_modules/lucide-react/dist/lucide-react.d.ts")],
            },
        },
        "include": ["src/**/*.ts", "src/**/*.tsx"],
    }
    tsconfig_path = SCRATCH / "tsconfig.json"
    tsconfig_path.write_text(json.dumps(build_tsconfig, indent=2) + "\n")

    tsc_bin = str(ROOT / "app/node_modules/typescript/bin/tsc")
    run("node", tsc_bin, "--project", str(tsconfig_path))

    shutil.copyfile(SRC / "styles.css", OUTPUT / "styles.css")
    shutil.copyfile(THIRD_PARTY_NOTICES, OUTPUT / THIRD_PARTY_NOTICES.name)

    verify_closed_imports()
    run("node", tsc_bin, "--project", str(PACKAGE / "tsconfig.contract.json"))

    shutil.rmtree(SCRATCH)

    ts_version = json.loads((ROOT / "app/node_modules/typescript/package.json").read_text())["version"]
    lucide_version = json.loads((PACKAGE / "package.json").read_text())["dependencies"]["lucide-react"]
    artifacts = sizes()
    report = {
        "target": "es2022-react-esm",
        "native_or_database_work": False,
        "tools": {
            "typescript_version": ts_version,
            "lucide_react_version": lucide_version,
        },
        "embedded_catalog": {
            "language": "en",
            "message_count": len(message_keys),
            "source_en_sha256": digest(ENGLISH_JSON),
            "engines_sha256": digest(ENGINES_JSON),
        },
        "models": models,
        "compression": {"gzip_level": 9, "brotli_quality": 11},
        "artifacts": artifacts,
    }
    (OUTPUT / "build-report.json").write_text(json.dumps(report, indent=2) + "\n")
    total_gzip = sum(item["gzip_bytes"] for item in artifacts.values())
    print(
        json.dumps(
            {
                "package": "@culpritsql/plan-viewer",
                "models": len(models),
                "messages": len(message_keys),
                "artifact_count": len(artifacts),
                "total_gzip_bytes": total_gzip,
            },
            indent=2,
        )
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check-prerequisites", action="store_true")
    options = parser.parse_args()
    if options.check_prerequisites:
        available = prerequisites()
        print(json.dumps(available, indent=2))
        raise SystemExit(bool(available["missing"]))
    build()


if __name__ == "__main__":
    main()
