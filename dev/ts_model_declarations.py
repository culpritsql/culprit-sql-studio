"""Package portable type-only declarations from existing ts-rs bindings."""
import hashlib
import re
from pathlib import Path

MODEL_IMPORT = re.compile(r'(from\s+["\'])(\./[^"\']+)(["\'])')


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def declaration_closure(roots: list[str], models_out: Path, bindings: Path) -> list[dict[str, object]]:
    pending = list(roots)
    found: dict[str, str] = {}
    while pending:
        name = pending.pop()
        if name in found:
            continue
        if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", name):
            raise ValueError(f"nonportable generated model reference: {name}")
        source = bindings / f"{name}.ts"
        text = source.read_text()
        if "This file was generated by [ts-rs]" not in text:
            raise ValueError(f"model is not existing ts-rs output: {source}")
        found[name] = text
        for match in MODEL_IMPORT.finditer(text):
            dependency = match[2][2:]
            if "/" in dependency or "." in dependency:
                raise ValueError(f"unexpected generated model import: {match[2]}")
            pending.append(dependency)
    models_out.mkdir(parents=True, exist_ok=True)
    manifest = []
    for name, text in sorted(found.items()):
        portable = MODEL_IMPORT.sub(lambda m: f"{m[1]}{m[2]}.js{m[3]}", text)
        target = models_out / f"{name}.d.ts"
        target.write_text(portable)
        manifest.append(
            {
                "name": name,
                "source_sha256": digest(bindings / f"{name}.ts"),
                "package_sha256": digest(target),
            }
        )
    return manifest
